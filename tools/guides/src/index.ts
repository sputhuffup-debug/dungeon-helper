/**
 * The docs pages of the modules' guides (`GameModule.guide`): one Markdown
 * page per built-in module that has a guide, generated from the same data the
 * app's Guide page renders, into docs/guides/<guide id>.md. `pnpm guides`
 * writes them; the test fails while a committed page is stale.
 *
 * The page is the guide's text with each step's screenshot
 * (docs/screenshots/guide-<module id>-<key>.png, written by the screenshot
 * script). "Take me there" links only exist in the app.
 */
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { guideDocFile, guideImageFile, guideSteps, moduleFromPackSource, type GameModule, type GuideDef, type PageRef } from "@campaign-forge/module-sdk";

/** Guide pages live here, relative to the repo root. */
export const GUIDES_DIR = "docs/guides";

/** The built-in modules (not the dev fixtures) whose guides get a docs page. */
export const BUILTIN_MODULES: Record<string, () => Promise<GameModule>> = {
  alien: async () => (await import("@campaign-forge/module-alien")).alienModule,
  "dnd5e-srd": async () => moduleFromPackSource((await import("@campaign-forge/module-dnd5e-srd")).dnd5eSrdSource),
  "pf2e-orc": async () => moduleFromPackSource((await import("@campaign-forge/module-pf2e-orc")).pf2eOrcSource),
};

/** A module's feature page in docs/features/, where its name is not the module id. */
export const FEATURE_PAGES: Record<string, string> = { "dnd5e-srd": "dnd5e", "pf2e-orc": "orc" };

export interface GuidePage {
  moduleId: string;
  /** Relative to the repo root, e.g. docs/guides/alien-first-campaign.md. */
  file: string;
  markdown: string;
}

/** GitHub's heading anchor: lowercase, punctuation dropped, spaces as dashes. */
export function headingAnchor(heading: string): string {
  return heading
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/\s/g, "-");
}

/** A printed page reference as the feature pages write it: "p. 158", "p. 244-252". */
export function pageText(page: PageRef): string {
  return Array.isArray(page) ? `p. ${page[0]}-${page[1]}` : `p. ${page}`;
}

export interface GuideMarkdownOptions {
  moduleId: string;
  moduleName: string;
  /** The module's feature page, relative to the guide page (e.g. ../features/alien.md). */
  featurePage?: string;
  /** Play mode names, for "Written for … play". */
  modeName?: (id: string) => string;
}

/** The guide as a Markdown page, its images beside it in ../screenshots/. */
export function guideMarkdown(guide: GuideDef, opts: GuideMarkdownOptions): string {
  const modeName = opts.modeName ?? ((id: string) => id);
  const out: string[] = [];
  out.push(`# ${guide.title}`, "");
  out.push(["[Campaign Forge](../../README.md)", ...(opts.featurePage ? [`[${opts.moduleName}](${opts.featurePage})`] : [])].join(" · "), "");
  out.push(`<!-- Generated by \`pnpm guides\` from the ${opts.moduleId} module's guide (${guide.id}); edit the module, not this page. -->`, "");
  out.push(guide.summary, "");
  const written = guide.mode && guide.mode.length > 0 ? ` Written for ${guide.mode.map(modeName).join(" or ")} play.` : "";
  out.push(`In the app, the same guide is the **Guide** page of every ${opts.moduleName} campaign (on Home, and on the setup checklist), where every step links straight to where it is done.${written}`, "");
  out.push("## Contents", "");
  guide.chapters.forEach((ch, i) => {
    const heading = `${i + 1}. ${ch.title}`;
    out.push(`${i + 1}. [${ch.title}](#${headingAnchor(heading)})`);
  });
  out.push("");
  const numbered = guideSteps(guide);
  guide.chapters.forEach((ch, i) => {
    out.push(`## ${i + 1}. ${ch.title}`, "");
    if (ch.intro) out.push(ch.intro, "");
    for (const { step, number } of numbered.filter((n) => n.chapter === ch)) {
      out.push(`### ${number} ${step.title}`, "");
      for (const p of step.body) out.push(p, "");
      const ref = step.page !== undefined ? pageText(step.page) : step.cite;
      if (ref) out.push(`*Rulebook: ${ref}.*`, "");
      if (step.image) out.push(`![${step.image.alt}](../screenshots/${guideImageFile(opts.moduleId, step.image.key)})`, "");
    }
  });
  return `${out.join("\n").replace(/\n+$/, "")}\n`;
}

/** Every built-in module's guide page (modules without a guide have none). */
export async function builtinGuidePages(root: string): Promise<GuidePage[]> {
  const out: GuidePage[] = [];
  for (const [id, load] of Object.entries(BUILTIN_MODULES)) {
    const module = await load();
    const guide = module.guide;
    if (!guide) continue;
    const feature = `docs/features/${FEATURE_PAGES[id] ?? id}.md`;
    out.push({
      moduleId: id,
      file: `${GUIDES_DIR}/${guideDocFile(guide)}`,
      markdown: guideMarkdown(guide, {
        moduleId: id,
        moduleName: module.manifest.name,
        ...(existsSync(resolve(root, feature)) ? { featurePage: `../features/${FEATURE_PAGES[id] ?? id}.md` } : {}),
        modeName: (m) => module.manifest.modes.find((x) => x.id === m)?.name ?? m,
      }),
    });
  }
  return out;
}
