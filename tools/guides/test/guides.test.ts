import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { GuideDef } from "@campaign-forge/module-sdk";
import { describe, expect, it } from "vitest";
import { builtinGuidePages, GUIDES_DIR, guideMarkdown, headingAnchor, pageText } from "../src/index";

const ROOT = resolve(fileURLToPath(new URL("../../../", import.meta.url)));

describe("the committed guide pages", () => {
  it("are what `pnpm guides` writes from the modules' guides (run it after changing a guide)", async () => {
    const pages = await builtinGuidePages(ROOT);
    expect(pages.map((p) => p.file)).toContain(`${GUIDES_DIR}/alien-first-campaign.md`);
    for (const page of pages) {
      const path = resolve(ROOT, page.file);
      expect(existsSync(path), `${page.file} is missing: run pnpm guides`).toBe(true);
      expect(readFileSync(path, "utf8"), `${page.file} is stale: run pnpm guides`).toBe(page.markdown);
    }
  }, 120_000);
});

const FIXTURE: GuideDef = {
  id: "fx.first-trip",
  title: "Your first trip",
  summary: "From nothing to the road.",
  mode: ["road"],
  chapters: [
    { id: "start", title: "Start the trip", intro: "One campaign.", steps: [{ id: "make", title: "Make it", body: ["Click *New campaign*.", "Name it."], image: { key: "make", alt: "The dialog" }, page: [10, 12], links: [{ label: "Home", page: "home" }] }] },
    { id: "go", title: "On the road, at last!", steps: [{ id: "go", title: "Go", body: ["Off you go."], cite: "Road book" }] },
  ],
};

describe("guideMarkdown", () => {
  const md = guideMarkdown(FIXTURE, { moduleId: "fx", moduleName: "Fixture", featurePage: "../features/fx.md", modeName: (m) => (m === "road" ? "Road" : m) });

  it("writes the title, the links back, a note that it is generated, the summary and the play mode", () => {
    expect(md.startsWith("# Your first trip\n\n[Campaign Forge](../../README.md) · [Fixture](../features/fx.md)\n")).toBe(true);
    expect(md).toContain("<!-- Generated by `pnpm guides` from the fx module's guide (fx.first-trip)");
    expect(md).toContain("From nothing to the road.");
    expect(md).toContain("Written for Road play.");
  });

  it("lists the chapters with working anchors and numbers the steps", () => {
    expect(md).toContain("1. [Start the trip](#1-start-the-trip)\n2. [On the road, at last!](#2-on-the-road-at-last)");
    expect(md).toContain("## 2. On the road, at last!");
    expect(md).toContain("### 1.1 Make it\n\nClick *New campaign*.\n\nName it.\n\n*Rulebook: p. 10-12.*\n\n![The dialog](../screenshots/guide-fx-make.png)");
    expect(md).toContain("### 2.1 Go\n\nOff you go.\n\n*Rulebook: Road book.*");
    // links are the app's: not in the page
    expect(md).not.toContain("](home)");
    expect(md.endsWith("\n") && !md.endsWith("\n\n")).toBe(true);
  });

  it("makes GitHub's heading anchors and the feature pages' page refs", () => {
    expect(headingAnchor("3. Connect them")).toBe("3-connect-them");
    expect(headingAnchor("1. The crew's ship")).toBe("1-the-crews-ship");
    expect(pageText(158)).toBe("p. 158");
    expect(pageText([244, 252])).toBe("p. 244-252");
  });
});
