/**
 * Builds the pack's JSON files.
 *
 *   pnpm --filter @campaign-forge/module-pf2e-orc build-pack -- --source <foundryvtt/pf2e checkout>
 *       converts the ORC core-book data (packs/pf2e/*, static/lang) into the
 *       part files (core-*.json), writes src/index.ts for them, then writes
 *       the authored files;
 *   pnpm --filter @campaign-forge/module-pf2e-orc build-pack
 *       rewrites only the authored files (pack.json, tables.json) from
 *       scripts/authored, reading the committed parts and generated data.
 *
 * The source checkout is read as data only (JSON.parse); nothing in it is
 * run. Output is deterministic: the same source gives byte-identical files.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { AUTHORED_PARTS, buildAuthored, type GeneratedData } from "./authored/index.ts";
import type { HpTable } from "./authored/entityTypes.ts";
import { convertSource, type Part } from "./convert.ts";
import { PACK } from "./ids.ts";

const here = dirname(fileURLToPath(import.meta.url));
export const PACK_DIR = resolve(here, "../pack");
const GENERATED = resolve(here, "generated");
const SRC_INDEX = resolve(here, "../src/index.ts");
const SRC_MANIFEST = resolve(here, "../src/manifest.ts");
const MAX_PART_BYTES = 2 * 1024 * 1024;

function write(file: string, data: unknown): number {
  const json = `${JSON.stringify(data, null, 1)}\n`;
  writeFileSync(file, json);
  return Buffer.byteLength(json);
}

function partFile(p: Part) {
  return { $schema: "../../module-sdk/schema/module-pack-part.schema.json", format: "campaign-forge-pack-part", formatVersion: 1, pack: PACK, name: p.name, ...(p.referenceLists ? { referenceLists: p.referenceLists } : {}), ...(p.rules ? { rules: p.rules } : {}), ...(p.presets ? { presets: p.presets } : {}) };
}


/** src/index.ts: one lazy import per part (a bundler gives each its own chunk). */
export function sourceIndex(parts: string[]): string {
  const lines = [...parts, ...AUTHORED_PARTS].map((p) => `    "${p}": json(() => import("../pack/${p}", { with: { type: "json" } })),`);
  return `/**
 * Fantasy d20 Remaster (ORC) as a built-in Campaign Forge data pack.
 *
 * The pack is plain JSON in \`pack/\`: the ORC-licensed core rules compatible
 * with the second edition remaster (Player Core, Player Core 2, GM Core and
 * Monster Core; see NOTICE) and the module's own tables, generators,
 * templates and play advice. Each file is loaded lazily, so a bundler gives
 * every one its own chunk.
 *
 * Generated by scripts/build-pack.ts (the part list follows the converted data).
 */
import type { PackSource } from "@campaign-forge/module-sdk";

const json = (load: () => Promise<{ default: unknown }>) => () => load().then((m) => m.default);

export const pf2eOrcSource: PackSource = {
  main: json(() => import("../pack/pack.json", { with: { type: "json" } })),
  parts: {
${lines.join("\n")}
  },
};

/** The pack's id. */
export const PF2E_ORC_ID = "${PACK}";
`;
}

/**
 * src/manifest.ts: the manifest fields the app's module registry shows before
 * the pack loads (name, play modes, licence and attribution), so they are not
 * copied by hand.
 */
export function sourceManifest(pack: Record<string, unknown>): string {
  const m = pack.manifest as Record<string, unknown>;
  const fields = { id: m.id, name: m.name, version: m.version, modes: m.modes, defaultMode: m.defaultMode, dataStatus: m.dataStatus, ruleset: m.ruleset, publisher: m.publisher, license: m.license };
  return `/**
 * The pack's manifest fields the app's module registry shows before the pack
 * loads (no pack data). Generated by scripts/build-pack.ts from pack.json.
 */
import type { ModuleManifest } from "@campaign-forge/module-sdk";

export const pf2eOrcManifest: Pick<ModuleManifest, "id" | "name" | "version" | "modes" | "defaultMode" | "dataStatus" | "ruleset" | "publisher" | "license"> = ${JSON.stringify(fields, null, 2)};
`;
}

/** The converted part files, in the order the pack joins them (pack.json lists them). */
export function convertedParts(): string[] {
  return JSON.parse(readFileSync(join(GENERATED, "parts.json"), "utf8")) as string[];
}

function readPart(name: string): Record<string, unknown> {
  return JSON.parse(readFileSync(join(PACK_DIR, name), "utf8")) as Record<string, unknown>;
}

/** What the authored files need from the converted data. */
export function generatedData(readJson: (name: string) => Record<string, unknown>, extra: Record<string, unknown>, parts: string[]): GeneratedData {
  const presets = parts.flatMap((p) => (readJson(p).presets as GeneratedData["presets"] | undefined) ?? []);
  const lists = parts.flatMap((p) => (readJson(p).referenceLists as GeneratedData["lists"] | undefined) ?? []);
  return { presets, lists, parts, ancestryHp: extra.ancestryHp as HpTable, classHp: extra.classHp as HpTable };
}

/**
 * Hit Points by ancestry and class for the character sheet: the module's own
 * (generated/hp.json) plus, when it was built, those of the built-in
 * supplement's ancestries and classes (generated/supplement-hp.json, numbers
 * only), nested under the supplement id, so a character with one of them gets
 * the right Hit Points while the supplement is on.
 */
export function readHp(generated = GENERATED): Record<string, unknown> {
  const hp = JSON.parse(readFileSync(join(generated, "hp.json"), "utf8")) as { ancestryHp: HpTable; classHp: HpTable };
  const file = join(generated, "supplement-hp.json");
  if (!existsSync(file)) return hp;
  const extra = JSON.parse(readFileSync(file, "utf8")) as { ancestryHp: Record<string, number>; classHp: Record<string, number> };
  const nest = (flat: Record<string, number>): HpTable => {
    const out: Record<string, Record<string, number>> = {};
    for (const [k, v] of Object.entries(flat)) {
      const dot = k.indexOf(".");
      if (dot < 0) throw new Error(`supplement Hit Points for "${k}": not a supplement id`);
      (out[k.slice(0, dot)] ??= {})[k.slice(dot + 1)] = v;
    }
    return out;
  };
  return { ancestryHp: { ...hp.ancestryHp, ...nest(extra.ancestryHp) }, classHp: { ...hp.classHp, ...nest(extra.classHp) } };
}

function main(argv: string[]): void {
  let source: string | undefined;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--") continue;
    if (argv[i] === "--source") source = argv[++i];
    else throw new Error(`unknown argument ${argv[i]}\nusage: build-pack [--source <foundryvtt/pf2e checkout>]`);
  }
  mkdirSync(PACK_DIR, { recursive: true });
  mkdirSync(GENERATED, { recursive: true });
  const sizes: Record<string, number> = {};
  if (source) {
    const out = convertSource(resolve(source));
    for (const f of readdirSync(PACK_DIR)) if (f.startsWith("core-")) rmSync(join(PACK_DIR, f));
    for (const p of out.parts) sizes[p.name] = write(join(PACK_DIR, p.name), partFile(p));
    const names = out.parts.map((p) => p.name);
    write(join(GENERATED, "parts.json"), names);
    write(join(GENERATED, "hp.json"), { ancestryHp: out.generated.ancestryHp, classHp: out.generated.classHp });
    write(join(GENERATED, "counts.json"), out.counts);
    writeFileSync(join(GENERATED, "conversion-notes.txt"), `${out.notes.join("\n")}\n`);
    console.log(JSON.stringify(out.counts, null, 1));
  }
  const parts = convertedParts();
  writeFileSync(SRC_INDEX, sourceIndex(parts));
  const hp = readHp();
  const authored = buildAuthored(generatedData(readPart, hp, parts));
  for (const [name, data] of Object.entries(authored)) sizes[name] = write(join(PACK_DIR, name), data);
  writeFileSync(SRC_MANIFEST, sourceManifest(authored["pack.json"] as Record<string, unknown>));
  for (const p of parts) if (!(p in sizes) && existsSync(join(PACK_DIR, p))) sizes[p] = Buffer.byteLength(readFileSync(join(PACK_DIR, p)));
  for (const [name, bytes] of Object.entries(sizes).sort()) {
    console.log(`${name.padEnd(24)} ${(bytes / 1024).toFixed(0).padStart(6)} KiB`);
    if (bytes > MAX_PART_BYTES) throw new Error(`${name} is over 2 MiB; split it`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
