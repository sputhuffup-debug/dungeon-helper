/**
 * Builds the built-in supplement "Remaster ORC books" (supplements/remaster-orc-books/).
 *
 *   pnpm --filter @campaign-forge/module-pf2e-orc build-supplement -- --source <foundryvtt/pf2e checkout>
 *       converts the allow-listed books into the supplement's main file and
 *       parts, writes src/supplement.ts and src/supplementManifest.ts, and
 *       the conversion notes;
 *   ... build-supplement -- --source <checkout> --candidates
 *       also prints capitalised words in the converted text that the module's
 *       own text never uses: the candidates for the Reserved Material list.
 *
 * The source is read as data only (JSON.parse); nothing in it is run. Output
 * is deterministic: the same source gives byte-identical files. The build
 * fails if any Reserved Material (outside the books' own citations) or any
 * Foundry markup is left in a file.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { ReferenceItem } from "@campaign-forge/module-sdk";
import { PACK_DIR } from "./build-pack.ts";
import { PART_BUDGET } from "./convert.ts";
import { TRADEMARK_NOTICE } from "./authored/manifest.ts";
import { attributionText, BOOKS, EXTENDS, SUPPLEMENT, SUPPLEMENT_NAME, SUPPLEMENT_VERSION } from "./supplement/books.ts";
import { candidates } from "./supplement/candidates.ts";
import { assertSupplementClean, baseModule, convertSupplementSource, type SupplementContent } from "./supplement/convert.ts";

const here = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = resolve(here, "..");
export const SUPPLEMENT_DIR = resolve(here, "../supplements/remaster-orc-books");
const GENERATED = resolve(here, "generated");
const MAX_FILE_BYTES = 2 * 1024 * 1024;
const SCHEMA_DIR = "../../../module-sdk/schema";

const minified = (x: unknown) => Buffer.byteLength(JSON.stringify(x));

interface PartBody {
  referenceItems?: Record<string, ReferenceItem[]>;
  referenceLists?: SupplementContent["referenceLists"];
  presets?: SupplementContent["creatures"];
  rules?: SupplementContent["rules"];
}

/**
 * Order-preserving packing into parts under the budget. Items for one of the
 * module's lists may continue in the next part (the parts are joined in
 * order); a new list, a preset or a rule card is never split.
 */
function packParts(prefix: string, units: Array<{ kind: "item"; listId: string; item: ReferenceItem } | { kind: "list"; list: SupplementContent["referenceLists"][number] } | { kind: "preset"; preset: SupplementContent["creatures"][number] } | { kind: "rule"; rule: SupplementContent["rules"][number] }>): Array<{ name: string; body: PartBody }> {
  const parts: Array<{ name: string; body: PartBody }> = [];
  let cur: PartBody = {};
  let size = 0;
  const flush = () => {
    if (Object.keys(cur).length) parts.push({ name: `${prefix}-${parts.length + 1}.json`, body: cur });
    cur = {};
    size = 0;
  };
  for (const u of units) {
    const v = u.kind === "item" ? u.item : u.kind === "list" ? u.list : u.kind === "preset" ? u.preset : u.rule;
    const n = minified(v);
    if (n > PART_BUDGET) throw new Error(`${prefix}: one entry is ${n} bytes, over the part budget`);
    if (size + n > PART_BUDGET) flush();
    if (u.kind === "item") ((cur.referenceItems ??= {})[u.listId] ??= []).push(u.item);
    else if (u.kind === "list") (cur.referenceLists ??= []).push(u.list);
    else if (u.kind === "preset") (cur.presets ??= []).push(u.preset);
    else (cur.rules ??= []).push(u.rule);
    size += n;
  }
  flush();
  if (parts.length === 1) parts[0]!.name = `${prefix}.json`;
  return parts;
}

/** src/supplement.ts: one lazy import per file (a bundler gives each its own chunk). */
export function supplementSourceModule(parts: string[]): string {
  const lines = parts.map((p) => `    "${p}": json(() => import("../supplements/remaster-orc-books/${p}", { with: { type: "json" } })),`);
  return `/**
 * The built-in supplement "${SUPPLEMENT_NAME}" for the module: the ORC-licensed
 * content of more remaster books (see NOTICE), as a split supplement. Each
 * file loads lazily, so a bundler gives every one its own chunk; the app
 * loads them only when the supplement is switched on.
 *
 * Generated by scripts/build-supplement.ts (the part list follows the converted data).
 */
import type { SupplementSource } from "@campaign-forge/module-sdk";

const json = (load: () => Promise<{ default: unknown }>) => () => load().then((m) => m.default);

export const pf2eOrcBooksSource: SupplementSource = {
  main: json(() => import("../supplements/remaster-orc-books/supplement.json", { with: { type: "json" } })),
  parts: {
${lines.join("\n")}
  },
};

/** The supplement's id. */
export const PF2E_ORC_BOOKS_ID = "${SUPPLEMENT}";
`;
}

/** src/supplementManifest.ts: what the module list shows before the supplement loads. */
export function supplementManifestModule(meta: Record<string, unknown>): string {
  return `/**
 * What the app's module list shows about the built-in supplement before it
 * loads (no supplement data). Generated by scripts/build-supplement.ts.
 */
import type { SupplementManifest } from "@campaign-forge/module-sdk";

export const pf2eOrcBooksManifest: Pick<SupplementManifest, "id" | "name" | "version" | "extends" | "licenseNotice" | "license" | "description" | "authors" | "dataStatus"> & {
  /** Entries it adds, per collection. */
  counts: Record<string, number>;
  /** Bytes of its JSON files (as shipped). */
  bytes: number;
} = ${JSON.stringify(meta, null, 2)};
`;
}

const json = (data: unknown) => `${JSON.stringify(data, null, 1)}\n`;

export interface SupplementBuild {
  /** Every file the build writes, by path relative to the package folder, with its exact text. */
  files: Record<string, string>;
  /** The part files' data (for the Reserved Material candidates). */
  parts: unknown[];
  counts: Record<string, unknown>;
}

/** Convert the source into the supplement's files (nothing is written; `main` writes them). Deterministic. */
export function buildSupplementFiles(root: string): SupplementBuild {
  // The attribution lines books.ts copies must be the source's own, word for word.
  const licence = readFileSync(join(root, "static", "licenses", "ORCLicense.md"), "utf8");
  for (const b of BOOKS) if (!b.todo && !licence.includes(b.attribution)) throw new Error(`${b.title}: the attribution line is not in the source's ORCLicense.md`);

  const out = convertSupplementSource(root, baseModule(PACK_DIR));
  const c = out.content;
  const itemsOf = (test: (listId: string) => boolean) => c.referenceItems.filter((l) => test(l.listId)).flatMap((l) => l.items.map((item) => ({ kind: "item" as const, listId: l.listId, item })));
  const groups: Array<[string, Parameters<typeof packParts>[1]]> = [
    ["reference", itemsOf((id) => /\.(conditions|actions|monster-abilities|familiar-abilities|vehicles)$/.test(id))],
    ["rules", c.rules.map((rule) => ({ kind: "rule" as const, rule }))],
    ["character", itemsOf((id) => /\.(ancestries|heritages|backgrounds|classes|class-features|ancestry-features)$/.test(id))],
    ["feats", [...itemsOf((id) => id.includes(".feats.")), ...c.referenceLists.filter((l) => l.id.includes(".feats.")).map((list) => ({ kind: "list" as const, list }))]],
    ["spells", itemsOf((id) => id.includes(".spells."))],
    ["equipment", itemsOf((id) => id.includes(".equipment."))],
    ["creatures", c.creatures.map((preset) => ({ kind: "preset" as const, preset }))],
    ["hazards", c.hazards.map((preset) => ({ kind: "preset" as const, preset }))],
  ];
  // Every item and list must land in a group.
  const placedItems = groups.reduce((n, [, u]) => n + u.filter((x) => x.kind === "item").length, 0);
  const allItems = c.referenceItems.reduce((n, l) => n + l.items.length, 0);
  if (placedItems !== allItems) throw new Error(`items placed in parts: ${placedItems} of ${allItems}; a list id fits no group`);
  if (c.referenceLists.some((l) => !l.id.includes(".feats."))) throw new Error(`new lists outside feats: ${c.referenceLists.filter((l) => !l.id.includes(".feats.")).map((l) => l.id).join(", ")}`);

  // "books-" names the chunks apart from the module's own "core-" ones (in a build, and in a precache rule if it ever needs one).
  const parts = groups.flatMap(([prefix, units]) => (units.length ? packParts(`books-${prefix}`, units) : []));
  const partFiles = parts.map((p) => ({ name: p.name, data: { $schema: `${SCHEMA_DIR}/module-supplement-part.schema.json`, format: "campaign-forge-supplement-part", formatVersion: 1, supplement: SUPPLEMENT, name: p.name, ...p.body } }));
  for (const p of partFiles) assertSupplementClean(p.name, p.data);

  const bookList = out.included.map((b) => b.cite);
  const manifest = {
    id: SUPPLEMENT,
    name: SUPPLEMENT_NAME,
    version: SUPPLEMENT_VERSION,
    extends: EXTENDS,
    licenseNotice: `ORC-licensed rules content (see attribution); JSON structure derived from the Foundry VTT pf2e system (Apache-2.0). ${TRADEMARK_NOTICE}`,
    license: { spdx: "LicenseRef-ORC", name: "ORC License", url: "https://paizo.com/orclicense", attribution: attributionText(out.included) },
    authors: ["Campaign Forge contributors (conversion)"],
    description: `More ORC content for the remaster rules from ${bookList.slice(0, -1).join(", ")} and ${bookList[bookList.length - 1]}: creatures, NPCs and hazards as presets, and ancestries, classes, feats, spells, items and actions in the module's lists. Reserved Material is left out.`,
    dataStatus: "partially-verified" as const,
  };
  const mainFile = { $schema: `${SCHEMA_DIR}/module-supplement.schema.json`, format: "campaign-forge-supplement", formatVersion: 1, manifest, parts: partFiles.map((p) => p.name) };

  const dir = "supplements/remaster-orc-books";
  const files: Record<string, string> = { [`${dir}/supplement.json`]: json(mainFile) };
  for (const p of partFiles) files[`${dir}/${p.name}`] = json(p.data);
  let bytes = 0;
  for (const [name, text] of Object.entries(files)) {
    const n = Buffer.byteLength(text);
    bytes += n;
    if (n > MAX_FILE_BYTES) throw new Error(`${name} is over 2 MiB; split it`);
  }
  const counts: Record<string, number> = { referenceItems: allItems, referenceLists: c.referenceLists.length, presets: c.creatures.length + c.hazards.length, rules: c.rules.length };
  files["src/supplement.ts"] = supplementSourceModule(partFiles.map((p) => p.name));
  files["src/supplementManifest.ts"] = supplementManifestModule({ ...manifest, counts, bytes });
  files["scripts/generated/supplement-counts.json"] = json(out.counts);
  files["scripts/generated/supplement-hp.json"] = json(out.hp);
  files["scripts/generated/supplement-notes.txt"] = `${out.notes.join("\n")}\n`;
  return { files, parts: partFiles.map((p) => p.data), counts: out.counts };
}

function main(argv: string[]): void {
  let source: string | undefined;
  let showCandidates = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--") continue;
    if (argv[i] === "--source") source = argv[++i];
    else if (argv[i] === "--candidates") showCandidates = true;
    else throw new Error(`unknown argument ${argv[i]}\nusage: build-supplement --source <foundryvtt/pf2e checkout> [--candidates]`);
  }
  if (!source) throw new Error("usage: build-supplement --source <foundryvtt/pf2e checkout> [--candidates]");
  const build = buildSupplementFiles(resolve(source));
  mkdirSync(SUPPLEMENT_DIR, { recursive: true });
  mkdirSync(GENERATED, { recursive: true });
  for (const f of readdirSync(SUPPLEMENT_DIR)) rmSync(join(SUPPLEMENT_DIR, f));
  let total = 0;
  for (const [name, text] of Object.entries(build.files)) {
    writeFileSync(join(PACKAGE_DIR, name), text);
    if (!name.startsWith("supplements/")) continue;
    total += Buffer.byteLength(text);
    console.log(`${name.slice(name.lastIndexOf("/") + 1).padEnd(24)} ${(Buffer.byteLength(text) / 1024).toFixed(0).padStart(6)} KiB`);
  }
  console.log(`total ${(total / 1024 / 1024).toFixed(2)} MiB`);
  console.log(JSON.stringify(build.counts.books, null, 1));
  console.log("Now rebuild the module's authored files (the sheet's Hit Points read generated/supplement-hp.json): pnpm --filter @campaign-forge/module-pf2e-orc build-pack");
  if (showCandidates) for (const line of candidates(PACK_DIR, build.parts)) console.log(line);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
